// ————————————————————————————————————————————————————————————————————————————
// naming —— 服务命名抽象 —— 文件总结
//
// 只有一个极简接口:能报出自己名字的东西就是 Namer。
// 它是 go-zero 各类"可命名组件"的统一约束 —— 典型实现是
// 服务发现客户端(zrpc 里每个直连/etcd 客户端都实现 Namer),
// 上层框架按 Name() 做注册表、监控归类、懒加载索引等。
// ————————————————————————————————————————————————————————————————————————————
package naming

// Namer interface wraps the method Name.
// 可命名组件接口:Name() 返回组件的逻辑名称
// (如 "diskbook-search.rpc",通常 = 服务名 + . + 类型)。
type Namer interface {
	Name() string
}
